import type { BoardDefinition, City, RouteDefinition, TicketDefinition } from "../model/board.js";
import { getRoutePoints } from "../engine/scoring.js";

const city = (id: string, name: string, region: City["region"]): City => ({
  id,
  name,
  region
});

const route = (
  cityA: string,
  cityB: string,
  length: RouteDefinition["length"],
  color: RouteDefinition["color"],
  parallelGroup?: string,
  variant = 1
): RouteDefinition => {
  const baseRoute: RouteDefinition = {
    id: parallelGroup
      ? `${parallelGroup}:${color}-${variant}`
      : `${cityA}-${cityB}-${color}-${length}`,
    cityA,
    cityB,
    length,
    color,
    points: getRoutePoints(length) as RouteDefinition["points"],
    isDoubleRoute: Boolean(parallelGroup),
    tags: [cityA, cityB, color, `len-${length}`]
  };

  return parallelGroup
    ? {
        ...baseRoute,
        parallelGroup
      }
    : baseRoute;
};

const ticket = (
  id: string,
  fromCity: string,
  toCity: string,
  points: number,
  family: TicketDefinition["family"]
): TicketDefinition => ({
  id,
  fromCity,
  toCity,
  points,
  family
});

